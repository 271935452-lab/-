def main():
    wb = load_workbook(PATH)
    ws = wb.active

    # 找「达成目标」列
    goal_col = None
    seq_col = None
    for c in range(1, ws.max_column + 1):
        h = ws.cell(2, c).value
        if h == "达成目标":
            goal_col = c
        if h == "序号":
            seq_col = c

    if not goal_col or not seq_col:
        raise SystemExit("未找到「达成目标」或「序号」列")

    wrap = Alignment(wrap_text=True, vertical="top")

    for r in range(3, ws.max_row + 1):
        seq = ws.cell(r, seq_col).value
        if seq is None:
            continue
        try:
            seq = int(seq)
        except (TypeError, ValueError):
            continue
        if seq not in GOALS:
            continue
        cell = ws.cell(r, goal_col)
        cell.value = GOALS[seq]
        cell.alignment = wrap

    # 列宽便于阅读
    from openpyxl.utils import get_column_letter

    col_letter = get_column_letter(goal_col)
    ws.column_dimensions[col_letter].width = 48

    wb.save(PATH)
    print(f"已填充 {len(GOALS)} 条「达成目标」→ {PATH}")


if __name__ == "__main__":
    main()
