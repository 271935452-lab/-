def write_fcl_change_log_sheet(wb, rows, sheet_title="需求变更记录"):
    ws = wb.create_sheet(sheet_title)

    ws.merge_cells("A1:J1")
    ws["A1"] = "整柜下单 · 需求变更记录"
    ws["A1"].font = TITLE_FONT
    ws["A1"].alignment = Alignment(horizontal="left", vertical="center")

    done = sum(1 for x in rows if x[6] == "已完成")
    proto = sum(1 for x in rows if x[6] == "原型已完成")
    review = sum(1 for x in rows if x[6] == "验收中")
    todo = sum(1 for x in rows if x[6] == "待开发")
    p0_todo = sum(1 for x in rows if x[6] == "待开发" and x[2] == "P0")
    ws.merge_cells("A2:J2")
    ws["A2"] = (
        f"整理日期：2026-07-06 · 来源：整柜流程7.2.docx · 共 {len(rows)} 项 · "
        f"原型已完成 {proto} · 验收中 {review} · 待开发 {todo}（P0 {p0_todo}）"
    )
    ws["A2"].font = SUB_FONT

    start_row = 4
    for col, h in enumerate(HEADERS, 1):
        c = ws.cell(row=start_row, column=col, value=h)
        c.font = HDR_FONT
        c.fill = HDR_FILL
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        c.border = BORDER

    for i, row in enumerate(rows, 1):
        r = start_row + i
        module, ctype, pri, desc, before, after, status, note = row
        req_id = f"ZG-{i:03d}"
        values = [i, req_id, module, ctype, pri, desc, before, after, status, note]
        for col, val in enumerate(values, 1):
            c = ws.cell(row=r, column=col, value=val)
            c.border = BORDER
            c.alignment = Alignment(vertical="top", wrap_text=True)
            if col == 5:
                if val == "P0":
                    c.fill = P0_FILL
                elif val == "P1":
                    c.fill = P1_FILL
            if col == 9:
                if val == "已完成":
                    c.fill = DONE_FILL
                elif val == "原型已完成":
                    c.fill = PROTO_FILL
                elif val == "验收中":
                    c.fill = TODO_FILL
                elif val == "待开发":
                    c.fill = TODO_FILL

    widths = [6, 10, 18, 12, 8, 36, 28, 36, 12, 20]
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w

    ws.freeze_panes = "A5"
    ws.row_dimensions[1].height = 28
    ws.row_dimensions[start_row].height = 32

    ws2 = wb.create_sheet("变更汇总")
    ws2["A1"] = "维度"
    ws2["B1"] = "数量"
    ws2["A1"].font = ws2["B1"].font = Font(bold=True)

    modules = {}
    statuses = {}
    priorities = {}
    for row in rows:
        modules[row[0]] = modules.get(row[0], 0) + 1
        statuses[row[6]] = statuses.get(row[6], 0) + 1
        priorities[row[2]] = priorities.get(row[2], 0) + 1

    r = 2
    ws2.cell(row=r, column=1, value="— 按状态 —").font = Font(bold=True)
    r += 1
    for k, v in sorted(statuses.items(), key=lambda x: -x[1]):
        ws2.cell(row=r, column=1, value=k)
        ws2.cell(row=r, column=2, value=v)
        r += 1
    r += 1
    ws2.cell(row=r, column=1, value="— 按优先级 —").font = Font(bold=True)
    r += 1
    for k in ("P0", "P1", "P2"):
        if k in priorities:
            ws2.cell(row=r, column=1, value=k)
            ws2.cell(row=r, column=2, value=priorities[k])
            r += 1
    r += 1
    ws2.cell(row=r, column=1, value="— 按功能模块 —").font = Font(bold=True)
    r += 1
    for k, v in sorted(modules.items(), key=lambda x: -x[1]):
        ws2.cell(row=r, column=1, value=k)
        ws2.cell(row=r, column=2, value=v)
        r += 1

    ws2.column_dimensions["A"].width = 22
    ws2.column_dimensions["B"].width = 10

    ws3 = wb.create_sheet("文档章节对照")
    ws3["A1"] = "文档章节"
    ws3["B1"] = "对应需求编号范围"
    ws3["A1"].font = ws3["B1"].font = Font(bold=True)
    sections = [
        ("一、客服・订单录入", "ZG-001 ~ ZG-014"),
        ("二、港前配套服务", "ZG-015 ~ ZG-019"),
        ("三、提交预报/修改派送", "ZG-020 ~ ZG-022"),
        ("四、报价 & 订舱", "ZG-023 ~ ZG-048"),
        ("五、截单 & 报关", "ZG-049 ~ ZG-054"),
        ("六、中转二程船期", "ZG-037"),
        ("七、目的港清关", "ZG-055 ~ ZG-056"),
        ("八、尾端派送", "ZG-057 ~ ZG-060"),
        ("九、人员权限绑定", "ZG-061 ~ ZG-062"),
        ("十、系统通用功能", "ZG-063 ~ ZG-068"),
        ("批注：货好时间/ETD·ETA", "ZG-006 ~ ZG-007"),
        ("批注：询价费用项/一件代发", "ZG-014、ZG-025 ~ ZG-028"),
    ]
    for i, (a, b) in enumerate(sections, 2):
        ws3.cell(row=i, column=1, value=a)
        ws3.cell(row=i, column=2, value=b)
    ws3.column_dimensions["A"].width = 28
    ws3.column_dimensions["B"].width = 24


