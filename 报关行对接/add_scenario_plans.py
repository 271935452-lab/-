def apply_plans(df: pd.DataFrame) -> pd.DataFrame:
    out = df.copy()
    us, them = [], []
    for _, row in out.iterrows():
        a, b = lookup_plan(row)
        us.append(a)
        them.append(b)
    out["方案（我们需做）"] = us
    out["方案（报关行需做）"] = them
    return out


def style_sheet(ws, col_count: int):
    header_fill = PatternFill("solid", fgColor="1F4E79")
    header_font = Font(color="FFFFFF", bold=True)
    wrap = Alignment(wrap_text=True, vertical="top")
    for col in range(1, col_count + 1):
        c = ws.cell(row=1, column=col)
        c.fill = header_fill
        c.font = header_font
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        ws.column_dimensions[get_column_letter(col)].width = 28 if col <= 5 else 48
    for row in range(2, ws.max_row + 1):
        ws.row_dimensions[row].height = 100
        for col in range(1, col_count + 1):
            ws.cell(row=row, column=col).alignment = wrap


def main():
    xl = pd.ExcelFile(SOURCE)
    sheets_data = {}
    for name in ["场景合并", "报关系统场景", "报关行场景"]:
        if name in xl.sheet_names:
            df = pd.read_excel(SOURCE, sheet_name=name)
            sheets_data[name] = apply_plans(df)

    overview = pd.DataFrame(OVERVIEW_ROWS)

    with pd.ExcelWriter(FILE, engine="openpyxl") as writer:
        overview.to_excel(writer, sheet_name="流程与方案总览", index=False)
        for name, df in sheets_data.items():
            df.to_excel(writer, sheet_name=name, index=False)
        if "报关行场景原图" in xl.sheet_names:
            try:
                img_df = pd.read_excel(SOURCE, sheet_name="报关行场景原图", header=None)
                img_df.to_excel(writer, sheet_name="报关行场景原图", index=False, header=False)
            except Exception:
                pass

    wb = load_workbook(FILE)
    for sn in ["流程与方案总览", "场景合并", "报关系统场景", "报关行场景"]:
        if sn in wb.sheetnames:
            style_sheet(wb[sn], wb[sn].max_column)
    wb.save(FILE)
    print(f"已更新：{FILE}")
    print(f"场景行数：{len(sheets_data.get('场景合并', []))}")
    print("新增 Sheet：流程与方案总览")


if __name__ == "__main__":
    main()
