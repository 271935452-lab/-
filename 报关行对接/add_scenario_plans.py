def lookup_plan(row):
    src = str(row.get("来源", "")).strip()
    cat = str(row.get("场景分类", "")).strip()
    sub = str(row.get("子场景", "")).strip()

    if cat == "分单号推送":
        key_split = (src, sub, "分单号推送")
        if key_split in PLANS:
            return PLANS[key_split]

    key = (src, sub)
    if key in PLANS:
        return PLANS[key]

    return ("待补充：请结合场景分类细化", "待补充：请与报关行确认是否支持申报前作废/重推")


