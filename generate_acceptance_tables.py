RESULT_COLORS = {
    "已验收": "C6EFCE",
    "验收中": "FFEB9C",
    "待验证": "FCE4D6",
    "未开始": "FFC7CE",
}

thin = Side(style="thin", color="BFBFBF")
border = Border(left=thin, right=thin, top=thin, bottom=thin)
wrap = Alignment(wrap_text=True, vertical="top")
center = Alignment(horizontal="center", vertical="center", wrap_text=True)


def style_header(ws, row, col_count):
    fill = PatternFill("solid", fgColor="4472C4")
    font = Font(bold=True, color="FFFFFF", size=11)
    for c in range(1, col_count + 1):
        cell = ws.cell(row=row, column=c)
        cell.fill = fill
        cell.font = font
        cell.alignment = center
        cell.border = border


def write_module(name, cfg):
    wb = Workbook()
    ws = wb.active
    ws.title = "验收进度总览"

    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=len(HEADERS))
    ws["A1"] = cfg["title"]
    ws["A1"].font = Font(bold=True, size=14)
    ws["A1"].alignment = Alignment(horizontal="center", vertical="center")
    ws.row_dimensions[1].height = 28

    ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=len(HEADERS))
    ws["A2"] = cfg["subtitle"]
    ws["A2"].font = Font(size=10, color="666666")
    ws["A2"].alignment = Alignment(horizontal="center", vertical="center")
    ws.row_dimensions[2].height = 20

    for col, h in enumerate(HEADERS, 1):
        ws.cell(row=3, column=col, value=h)
    style_header(ws, 3, len(HEADERS))

    start_row = 4
    for i, row in enumerate(cfg["rows"]):
        r = start_row + i
        for col, val in enumerate(row, 1):
            cell = ws.cell(row=r, column=col, value=val)
            cell.border = border
            cell.alignment = wrap if col not in (3, 4) else center
            if col == 6:
                color = RESULT_COLORS.get(val)
                if color:
                    cell.fill = PatternFill("solid", fgColor=color)

    widths = [14, 36, 14, 14, 12, 10, 18, 42]
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w

    for r in range(start_row, start_row + len(cfg["rows"])):
        ws.row_dimensions[r].height = 36

    path = OUT_DIR / f"验收进度-{name}.xlsx"
    if cfg.get("change_log"):
        write_change_log_sheet(wb, COMMISSION_CHANGE_ROWS)
    wb.save(path)
    return path


def main():
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    paths = []
    for name, cfg in MODULES.items():
        paths.append(write_module(name, cfg))
    for p in paths:
        print(f"已生成: {p}")


if __name__ == "__main__":
    main()
