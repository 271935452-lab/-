(function syncShipStowPinNumbers() {
  var points = window.SHIP_STOW_REVIEW_POINTS || [];
  var pinIds = window.SHIP_STOW_REVIEW_PIN_IDS || {};
  Object.keys(pinIds).forEach(function (pageKey) {
    var page = Number(pageKey);
    var byId = {};
    points.forEach(function (p) {
      if (p.page === page) byId[p.id] = p;
    });
    (pinIds[pageKey] || []).forEach(function (id, i) {
      if (byId[id]) byId[id].pin = i + 1;
    });
  });
})();
