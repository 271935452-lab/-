def highlight_focus_cells(ws, col_letter, start_row=2):
    fill = PatternFill("solid", fgColor="FFF7E6")
    bold = Font(bold=True, color="AD4E00")
    wrap = Alignment(wrap_text=True, vertical="top")
    for row in range(start_row, ws.max_row + 1):
        cell = ws[f"{col_letter}{row}"]
        if cell.value:
            cell.fill = fill
            cell.font = bold
            cell.alignment = wrap


def style_ws(ws, header_fill="1F4E79"):
    thin = Side(style="thin", color="CCCCCC")
    border = Border(left=thin, right=thin, top=thin, bottom=thin)
    hfill = PatternFill("solid", fgColor=header_fill)
    hfont = Font(color="FFFFFF", bold=True)
    wrap = Alignment(wrap_text=True, vertical="top")
    for col in range(1, ws.max_column + 1):
        c = ws.cell(row=1, column=col)
        c.fill = hfill
        c.font = hfont
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        letter = get_column_letter(col)
        ws.column_dimensions[letter].width = min(50, max(12, len(str(c.value or "")) + 2))
    for row in range(2, ws.max_row + 1):
        ws.row_dimensions[row].height = 60
        for col in range(1, ws.max_column + 1):
            cell = ws.cell(row=row, column=col)
            cell.alignment = wrap
            cell.border = border


